//! Compiles libdivecomputer from `third_party/libdivecomputer` (git submodule)
//! as a static library. Only parsing is used: no USB, Bluetooth or serial
//! transport is enabled, so no external library is needed.

use std::path::PathBuf;
use std::{env, fs};

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap())
        .join("../third_party/libdivecomputer");
    let src = root.join("src");
    let include = root.join("include");
    assert!(
        src.join("parser.c").exists(),
        "libdivecomputer sources missing: run `git submodule update --init`"
    );
    println!("cargo:rerun-if-changed={}", src.display());
    println!("cargo:rerun-if-changed={}", include.display());

    // version.h is normally generated by ./configure.
    let configure = fs::read_to_string(root.join("configure.ac")).unwrap();
    let m4 = |name: &str| -> String {
        let key = format!("m4_define([{name}],[");
        let start = configure
            .find(&key)
            .unwrap_or_else(|| panic!("{name} not in configure.ac"))
            + key.len();
        configure[start..].split(']').next().unwrap().to_string()
    };
    let (major, minor, micro, suffix) = (
        m4("dc_version_major"),
        m4("dc_version_minor"),
        m4("dc_version_micro"),
        m4("dc_version_suffix"),
    );
    let version = if suffix.is_empty() {
        format!("{major}.{minor}.{micro}")
    } else {
        format!("{major}.{minor}.{micro}-{suffix}")
    };
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let gen_include = out.join("include");
    fs::create_dir_all(gen_include.join("libdivecomputer")).unwrap();
    let header = fs::read_to_string(include.join("libdivecomputer/version.h.in"))
        .unwrap()
        .replace("@DC_VERSION@", &version)
        .replace("@DC_VERSION_MAJOR@", &major)
        .replace("@DC_VERSION_MINOR@", &minor)
        .replace("@DC_VERSION_MICRO@", &micro);
    fs::write(gen_include.join("libdivecomputer/version.h"), header).unwrap();
    // revision.h is normally generated from `git rev-parse HEAD`; the
    // submodule commit is pinned, so a fixed label is enough.
    fs::write(
        gen_include.join("revision.h"),
        "#define DC_VERSION_REVISION \"divelens\"\n",
    )
    .unwrap();

    let windows = env::var("CARGO_CFG_TARGET_OS").unwrap() == "windows";
    let msvc = env::var("CARGO_CFG_TARGET_ENV").unwrap() == "msvc";
    let mut build = cc::Build::new();
    build
        .include(&gen_include)
        .include(&include)
        .include(&src)
        .warnings(false)
        .define("PACKAGE_VERSION", Some(format!("\"{version}\"").as_str()));
    if !suffix.is_empty() {
        build.define("HAVE_VERSION_SUFFIX", None);
    }
    if windows {
        build.define("WIN32", None).define("_WINDOWS", None);
        if msvc {
            build.define("_CRT_SECURE_NO_WARNINGS", None);
        }
    } else {
        for d in [
            "HAVE_UNISTD_H",
            "HAVE_PTHREAD_H",
            "HAVE_SYS_PARAM_H",
            "HAVE_LOCALTIME_R",
            "HAVE_GMTIME_R",
            "HAVE_TIMEGM",
            "HAVE_CLOCK_GETTIME",
        ] {
            build.define(d, None);
        }
        if env::var("CARGO_CFG_TARGET_OS").unwrap() == "macos" {
            build
                .define("HAVE_MACH_MACH_TIME_H", None)
                .define("HAVE_MACH_ABSOLUTE_TIME", None);
        }
    }

    let mut files: Vec<PathBuf> = fs::read_dir(&src)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "c"))
        .filter(|p| {
            let name = p.file_name().unwrap().to_str().unwrap();
            if windows {
                name != "serial_posix.c"
            } else {
                name != "serial_win32.c"
            }
        })
        .collect();
    files.sort();
    build.files(&files).compile("divecomputer");

    if windows {
        println!("cargo:rustc-link-lib=ws2_32");
    }
}
